#ifndef CSV_H
#define CSV_H

#include <stdio.h>

// запись == строка

typedef struct {
    char **fields; // массив строк — значений полей записи
    int *quoted; // флаги: было ли поле в кавычках
    int count; // сколько полей уже добавлено (занято)
    int capacity; // на сколько полей выделена память (всего слотов)
    size_t raw_length; // сколько байт заняла запись в файле, включая кавычки, запятые, пробелы, разделители
} CsvRecord;

// инициализирует запись пустым состоянием
void csv_record_init(CsvRecord *rec);

// освобождает всю память
void csv_record_free(CsvRecord *rec);

// читает запись из файла и заполняет rec; разбивает строку на поля
/* возвращает:
    1 - запись прочитана, rec заполнена
    0 - достигнут конец файла
    -1 - ошибка (завершить работу с кодом 1)
*/
int  csv_read_record(FILE *f, CsvRecord *rec);

/* возвращает:
    1 - строка пуста или состоит только из пробелов и табуляций
    0 - иначе
*/
int  csv_is_blank(const char *s);

#endif